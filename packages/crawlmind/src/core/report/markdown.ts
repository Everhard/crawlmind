import type { TopPage } from '../analysis/audit.js';
import type { Severity } from '../analysis/checks.js';
import { VERSION } from '../version.js';
import type { ReportData } from './data.js';

const REPO = 'https://github.com/Everhard/crawlmind';
const ICON: Record<Severity, string> = { critical: '🔴', warning: '🟠', info: '🔵' };

/** Escape characters that would break Markdown tables or formatting. */
export function escapeMarkdown(text: string): string {
  return text.replace(/[\\`*_[\]<>|]/g, (c) => `\\${c}`).replace(/\s+/g, ' ');
}

const m = escapeMarkdown;
const num = (n: number) => n.toLocaleString('en-US');
const plural = (n: number, word: string) => `${num(n)} ${word}${n === 1 ? '' : 's'}`;
const ms = (v: number | null) => (v === null ? '—' : `${Math.round(v)} ms`);
const rel = (url: string, site: string) =>
  url.startsWith(site) ? url.slice(site.length) || '/' : url;

function pageTable(pages: TopPage[], site: string): string[] {
  if (pages.length === 0) return ['None.'];
  return [
    '| Page | PageRank | Inlinks | In content | Depth | TTFB |',
    '| --- | ---: | ---: | ---: | ---: | ---: |',
    ...pages.map(
      (p) =>
        `| ${m(rel(p.url, site))} | ${p.pagerankScore ?? '—'} | ${num(p.inlinks)} | ${num(p.mainInlinks)} | ${p.clickDepth ?? '—'} | ${ms(p.ttfbMs)} |`,
    ),
  ];
}

export function renderMarkdownReport(data: ReportData): string {
  const { summary: s } = data;
  const site = s.crawl.site;
  const t = s.totals;
  const lines: string[] = [
    `# SEO audit: ${m(new URL(site).host)}`,
    '',
    `${site} · crawled ${s.crawl.startedAt.slice(0, 10)} · ${num(s.crawl.pagesCrawled)} pages · crawl \`${s.crawl.crawlId}\``,
    '',
    '## Summary',
    '',
    `- **Issues:** ${num(s.issueCounts.critical)} critical, ${plural(s.issueCounts.warning, 'warning')}, ${plural(s.issueCounts.info, 'notice')}`,
    `- **Pages:** ${num(t.pages)} (${num(t.htmlPages)} HTML, ${num(t.indexablePages)} indexable)`,
    `- **Status codes:** 2xx ${num(t.status['2xx'])}, 3xx ${num(t.status['3xx'])}, 4xx ${num(t.status['4xx'])}, 5xx ${num(t.status['5xx'])}, failed ${num(t.status.failed)}, blocked ${num(t.status.blocked)}`,
    `- **Links:** ${num(t.internalLinks)} internal, ${num(t.externalLinks)} external targets`,
    `- **TTFB:** median ${ms(s.ttfbMs.median)}, p90 ${ms(s.ttfbMs.p90)}`,
    '',
    '## Issues',
    '',
  ];
  if (data.issues.length === 0) lines.push('No issues found.', '');
  for (const issue of data.issues) {
    lines.push(`### ${ICON[issue.severity]} ${m(issue.title)} (${num(issue.count)})`, '');
    for (const x of issue.examples) {
      lines.push(
        `- ${m(rel(x.url, site))}${x.detail ? ` — ${m(x.detail.replaceAll(site, ''))}` : ''}`,
      );
    }
    if (issue.count > issue.examples.length)
      lines.push(`- … and ${num(issue.count - issue.examples.length)} more`);
    lines.push('', `**Fix:** ${m(issue.recommendation)} (\`${issue.id}\`)`, '');
  }
  lines.push(
    '## Important pages that need more links',
    '',
    ...pageTable(data.underlinked, site),
    '',
  );
  lines.push('## Strongest pages (internal PageRank)', '', ...pageTable(data.topPages, site), '');
  lines.push('## Slowest pages (TTFB)', '', ...pageTable(data.slowestPages, site), '');
  lines.push(
    '---',
    '',
    `Generated by [Crawlmind](${REPO}) ${VERSION} on ${data.generatedAt.slice(0, 16).replace('T', ' ')} UTC.`,
    '',
  );
  return lines.join('\n');
}

import { mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import type { CrawlDiff, Engine } from '../../src/core/index.js';
import { runCliCaptured } from '../helpers/cli.js';
import { crawlAndWait, createTestEngine } from '../helpers/engine.js';
import { startFixtureSites } from '../helpers/fixture-server.js';

describe('crawl diff and reports', () => {
  let sites: Awaited<ReturnType<typeof startFixtureSites>>;
  let engine: Engine;
  let first: string;
  let second: string;
  let diff: CrawlDiff;
  let dir: string;
  const p = (path: string) => `${sites.site.origin}${path}`;

  beforeAll(async () => {
    sites = await startFixtureSites();
    engine = createTestEngine();
    dir = mkdtempSync(join(tmpdir(), 'crawlmind-report-'));
    first = (await crawlAndWait(engine, { url: sites.site.origin, checkExternalLinks: false }))
      .crawlId;

    // The site changes between crawls.
    const { routes } = sites.site;
    routes['/about'] = { status: 404, body: 'gone' };
    routes['/missing'] = {
      body: '<html><head><title>Back</title></head><body><main><p>Back again.</p></main></body></html>',
    };
    routes['/products/'] = { ...routes['/products/'], delayMs: 400 };
    routes['/blog/post-1'] = {
      body: '<html><head><title>Post 1, renamed</title><link rel="canonical" href="/blog/"></head><body><main><h1>Post 1</h1></main></body></html>',
    };
    second = (await crawlAndWait(engine, { url: sites.site.origin, checkExternalLinks: false }))
      .crawlId;
    diff = engine.compare(second, first); // order does not matter
  });

  afterAll(async () => {
    await engine.close();
    await sites.close();
    rmSync(dir, { recursive: true, force: true });
  });

  it('orders crawls chronologically', () => {
    expect(diff.before.crawlId).toBe(first);
    expect(diff.after.crawlId).toBe(second);
  });

  it('finds new and fixed errors and broken links', () => {
    expect(diff.newErrors.items).toContainEqual({ url: p('/about'), before: 200, after: 404 });
    expect(diff.fixedErrors.items).toContainEqual({ url: p('/missing'), before: 404, after: 200 });
    expect(diff.newBrokenLinks.items.some((l) => l.target === p('/about'))).toBe(true);
    expect(diff.fixedBrokenLinks.items.some((l) => l.target === p('/missing'))).toBe(true);
  });

  it('finds TTFB regressions, title and canonical changes, inlink changes', () => {
    expect(diff.ttfbRegressions.items.map((r) => r.url)).toEqual([p('/products/')]);
    expect(diff.titleChanges.items).toContainEqual({
      url: p('/blog/post-1'),
      before: 'Post 1',
      after: 'Post 1, renamed',
    });
    expect(diff.canonicalChanges.items).toContainEqual({
      url: p('/blog/post-1'),
      before: null,
      after: p('/blog/'),
    });
    // post-1 no longer links to post-2.
    expect(diff.inlinksLost.items.some((c) => c.url === p('/blog/post-2'))).toBe(true);
    expect(diff.issueCounts.some((c) => c.checkId === 'links.broken_internal')).toBe(true);
  });

  it('writes a self-contained, escaped HTML report', () => {
    const result = engine.exportReport(second, { format: 'html', path: join(dir, 'audit.html') });
    const html = readFileSync(result.path, 'utf8');
    expect(html).toMatch(/^<!doctype html>/);
    expect(html).toContain('<meta name="viewport"');
    expect(html).toContain(
      'Generated by <a href="https://github.com/Everhard/crawlmind">Crawlmind</a>',
    );
    expect(html).toContain('Broken internal links');
    expect(html).not.toMatch(/<script|<link rel="stylesheet"/i);
    expect(html).not.toMatch(/https?:\/\/(?!127\.0\.0\.1|github\.com)[^"' ]+\.(css|js)/);
  });

  it('writes a Markdown report', () => {
    const result = engine.exportReport(second, { format: 'markdown', path: join(dir, 'audit.md') });
    const md = readFileSync(result.path, 'utf8');
    expect(md).toMatch(/^# SEO audit: 127\.0\.0\.1:\d+/);
    expect(md).toContain('## Speed by template');
    expect(md).toContain('Generated by [Crawlmind](https://github.com/Everhard/crawlmind)');
  });

  it('refuses unsafe report paths', () => {
    const existing = join(dir, 'keep.html');
    writeFileSync(existing, 'mine');
    expect(() => engine.exportReport(second, { format: 'html', path: existing })).toThrow(
      /already exists/,
    );
    expect(readFileSync(existing, 'utf8')).toBe('mine');
    expect(() => engine.exportReport(second, { format: 'html', path: join(dir, 'x.sh') })).toThrow(
      /must end in/,
    );
    expect(() =>
      engine.exportReport(second, { format: 'html', path: join(dir, 'no/such/dir.html') }),
    ).toThrow(/does not exist/);
    expect(
      engine.exportReport(second, { format: 'html', path: existing, overwrite: true }).bytes,
    ).toBeGreaterThan(1000);
  });

  it('refuses symlinks and, when restricted, paths outside the reports directory', () => {
    const previousHome = process.env.CRAWLMIND_HOME;
    process.env.CRAWLMIND_HOME = join(dir, 'home');
    try {
      const outside = join(dir, 'outside.html');
      expect(() =>
        engine.exportReport(second, { format: 'html', path: outside, restrictToReportsDir: true }),
      ).toThrow(/only write reports inside/);

      const inDefault = engine.exportReport(second, { format: 'html', restrictToReportsDir: true });
      expect(inDefault.path.startsWith(join(dir, 'home', 'reports'))).toBe(true);

      const victim = join(dir, 'victim.md');
      writeFileSync(victim, 'keep me');
      const link = join(dir, 'home', 'reports', 'link.md');
      symlinkSync(victim, link);
      expect(() =>
        engine.exportReport(second, {
          format: 'markdown',
          path: link,
          overwrite: true,
          restrictToReportsDir: true,
        }),
      ).toThrow(/symbolic link/);
      expect(readFileSync(victim, 'utf8')).toBe('keep me');
    } finally {
      if (previousHome === undefined) delete process.env.CRAWLMIND_HOME;
      else process.env.CRAWLMIND_HOME = previousHome;
    }
  });

  it('refuses to compare different sites', async () => {
    const other = await startFixtureSites();
    const id = (
      await crawlAndWait(engine, { url: other.site.origin, maxPages: 2, checkExternalLinks: false })
    ).crawlId;
    expect(() => engine.compare(first, id)).toThrow(/different sites/);
    await other.close();
  });
});


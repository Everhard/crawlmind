describe('CLI diff and report', () => {
  it('compares the two latest crawls and writes a report', async () => {
    const sites = await startFixtureSites();
    const home = mkdtempSync(join(tmpdir(), 'crawlmind-cli-diff-'));
    const base = ['--home', home, '--no-color'];
    const crawl = ['crawl', sites.site.origin, '--allow-private', '--delay', '0', '--no-external'];
    await runCliCaptured([...base, '--json', ...crawl]);
    sites.site.routes['/about'] = { status: 500, body: 'down' };
    await runCliCaptured([...base, '--json', ...crawl]);

    const diff = await runCliCaptured([...base, 'diff']);
    expect(diff.stdout).toMatch(/New errors\s+1/);
    expect(diff.stdout).toContain('/about  200 → 500');

    const report = await runCliCaptured([...base, 'report', '-f', 'md']);
    expect(report.stdout).toMatch(/Wrote .*reports\/127\.0\.0\.1-[\w-]+\.md/);

    await sites.close();
    rmSync(home, { recursive: true, force: true });
  });
});
